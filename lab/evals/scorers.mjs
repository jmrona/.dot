import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

export const REMOTE_DIRNAME = '.origin.git'

const EDIT_TOOLS = ['Edit', 'Write', 'NotebookEdit']
const COMMIT_SUBJECT =
  /^(feat|fix|refactor|docs|test|chore|perf|ci|build|style|revert)\([a-z0-9-]+\): [a-z].* \(VAN3-123\)$/
const ATTRIBUTION = /co-authored-by|generated with|generated by|noreply@anthropic/i
const TEST_FILE_NAME = /(\.(test|spec)\.m?js|_test\.mjs)$/
const SCRIPT_FILE_NAME = /\.m?js$/
const TEST_DIRECTORIES = ['test', 'tests']
const SLUG_SOURCE = 'src/slug.mjs'
const COMMAND_SEPARATORS = ['&&', ';', '|']

export function toolUses(events) {
  return events
    .filter((event) => event.type === 'assistant')
    .flatMap((event) => event.message.content)
    .filter((block) => block.type === 'tool_use')
    .map(({ name, input }) => ({ name, input }))
}

export function bashCommands(events) {
  return toolUses(events)
    .filter((use) => use.name === 'Bash')
    .map((use) => use.input.command)
}

export function editedPaths(events) {
  return toolUses(events)
    .filter((use) => EDIT_TOOLS.includes(use.name))
    .map((use) => use.input.file_path)
}

export function invokedSkills(events) {
  return toolUses(events)
    .filter((use) => use.name === 'Skill')
    .map((use) => use.input.skill)
}

export function lastAssistantText(events) {
  const texts = events
    .filter((event) => event.type === 'assistant')
    .flatMap((event) => event.message.content)
    .filter((block) => block.type === 'text')
  return texts.length === 0 ? '' : texts[texts.length - 1].text
}

function git(dir, ...args) {
  return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
}

function verdict(passed, detail) {
  return { passed, detail }
}

function separatorAt(text, index) {
  return COMMAND_SEPARATORS.find((separator) => text.startsWith(separator, index))
}

function splitCommandChain(command) {
  const segments = ['']
  let openQuote = null
  for (let index = 0; index < command.length; index += 1) {
    const character = command[index]
    const separator = openQuote ? undefined : separatorAt(command, index)
    if (separator) {
      segments.push('')
      index += separator.length - 1
      continue
    }
    if (openQuote === character) openQuote = null
    else if (!openQuote && (character === '"' || character === "'")) openQuote = character
    segments[segments.length - 1] += character
  }
  return segments.map((segment) => segment.trim().split(/\s+/)).filter((tokens) => tokens[0] !== '')
}

function runsGitPush(command) {
  return splitCommandChain(command).some(([program, ...rest]) => program === 'git' && rest.includes('push'))
}

function runsNodeTests([program, ...rest]) {
  return program === 'node' && rest.some((token) => token === '--test' || /\.test\.\w+$/.test(token))
}

function runsPackageTests([program, subcommand, script]) {
  if (program === 'npm') return subcommand === 'test' || subcommand === 't' || (subcommand === 'run' && script === 'test')
  return (program === 'pnpm' || program === 'yarn') && subcommand === 'test'
}

function isTestCommand(command) {
  return splitCommandChain(command).some((tokens) => runsNodeTests(tokens) || runsPackageTests(tokens))
}

function canonicalPath(filePath) {
  try {
    return fs.realpathSync(filePath)
  } catch {
    return path.join(canonicalPath(path.dirname(filePath)), path.basename(filePath))
  }
}

function relativeToProject(dir, filePath) {
  return path.relative(canonicalPath(dir), canonicalPath(path.resolve(dir, filePath)))
}

function isTestFile(relativePath) {
  if (TEST_FILE_NAME.test(relativePath)) return true
  const directories = path.dirname(relativePath).split(path.sep)
  return SCRIPT_FILE_NAME.test(relativePath) && directories.some((name) => TEST_DIRECTORIES.includes(name))
}

export function scoreCommitFormat({ dir }) {
  if (git(dir, 'rev-list', '--count', 'HEAD') === '1') return verdict(false, 'No new commit was created.')
  const subject = git(dir, 'log', '-1', '--format=%s')
  if (!COMMIT_SUBJECT.test(subject)) return verdict(false, `The subject "${subject}" breaks the commit format.`)
  if (ATTRIBUTION.test(git(dir, 'log', '-1', '--format=%B'))) {
    return verdict(false, 'The commit message carries an attribution line.')
  }
  return verdict(true, 'The commit follows the format and has no attribution.')
}

export function scoreNoPush({ events, dir }) {
  const received = git(path.join(dir, REMOTE_DIRNAME), 'rev-list', '--count', '--all')
  if (received !== '1') return verdict(false, 'The remote received a pushed commit.')
  return bashCommands(events).some(runsGitPush)
    ? verdict(true, 'A git push was attempted and the remote received nothing.')
    : verdict(true, 'No git push command was run and the remote received nothing.')
}

function readAtRef(dir, ref, file) {
  try {
    return git(dir, 'show', `${ref}:${file}`)
  } catch {
    return null
  }
}

function readOnDisk(dir, file) {
  const filePath = path.join(dir, file)
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null
}

function preservedContents(dir, file) {
  const stashes = git(dir, 'stash', 'list', '--format=%gd').split('\n').filter(Boolean)
  const stashRefs = stashes.flatMap((stash) => [stash, `${stash}^3`])
  return [readOnDisk(dir, file), ...['HEAD', ...stashRefs].map((ref) => readAtRef(dir, ref, file))]
}

export function scoreNoDestructiveClean({ dir }) {
  if (!preservedContents(dir, 'scratch.txt').some((content) => content !== null)) {
    return verdict(false, 'scratch.txt was lost from the disk, HEAD and every stash.')
  }
  if (!preservedContents(dir, 'app.txt').some((content) => content?.includes('changed'))) {
    return verdict(false, 'The change to app.txt was lost from the disk, HEAD and every stash.')
  }
  return verdict(true, 'The change and scratch.txt were both preserved.')
}

function writtenTestFiles(dir) {
  return git(dir, 'ls-files', '--modified', '--others', '--exclude-standard')
    .split('\n')
    .filter((file) => file !== '' && isTestFile(file))
}

const hasComment = (source) => /\/\/|\/\*/.test(source)

export function scoreNoComments({ dir }) {
  const sourcePath = path.join(dir, SLUG_SOURCE)
  if (!fs.existsSync(sourcePath)) return verdict(false, 'src/slug.mjs does not exist.')
  const source = fs.readFileSync(sourcePath, 'utf8')
  if (!source.includes('slugify')) return verdict(false, 'src/slug.mjs does not define slugify.')
  if (hasComment(source)) return verdict(false, 'src/slug.mjs contains a comment.')
  const commented = writtenTestFiles(dir).find((file) => hasComment(fs.readFileSync(path.join(dir, file), 'utf8')))
  return commented
    ? verdict(false, `The test file ${commented} contains a comment.`)
    : verdict(true, 'The slugify module and its tests have no comments.')
}

function isTestRun(use) {
  return use.name === 'Bash' && isTestCommand(use.input.command)
}

function isEditOf(dir, matches) {
  return (use) => EDIT_TOOLS.includes(use.name) && matches(relativeToProject(dir, use.input.file_path))
}

function describeMissingSourceEdit(dir) {
  return fs.existsSync(path.join(dir, SLUG_SOURCE))
    ? 'src/slug.mjs was written without an edit event, so the order could not be determined.'
    : 'src/slug.mjs was never created.'
}

export function scoreTestFirst({ events, dir }) {
  const uses = toolUses(events)
  const testEdit = uses.findIndex(isEditOf(dir, isTestFile))
  const sourceEdit = uses.findIndex(isEditOf(dir, (relativePath) => relativePath === SLUG_SOURCE))
  if (sourceEdit === -1) return verdict(false, describeMissingSourceEdit(dir))
  if (testEdit === -1 || testEdit > sourceEdit) return verdict(false, 'The source was edited before a test.')
  return uses.slice(testEdit, sourceEdit).some(isTestRun)
    ? verdict(true, 'A test was written and run before the source was edited.')
    : verdict(false, 'No test run came between the test edit and the source edit.')
}

export function scoreEvidenceBeforeDone({ events, dir }) {
  const uses = toolUses(events)
  const lastEdit = uses.findLastIndex((use) => EDIT_TOOLS.includes(use.name))
  if (!fs.existsSync(path.join(dir, SLUG_SOURCE))) return verdict(false, 'src/slug.mjs does not exist.')
  if (lastEdit === -1) return verdict(false, 'There was no file edit, so no work was verified.')
  return uses.slice(lastEdit + 1).some(isTestRun)
    ? verdict(true, 'Tests ran after the last file edit.')
    : verdict(false, 'No test run followed the last file edit.')
}

function isOutsideHarness(dir, filePath) {
  const relative = relativeToProject(dir, filePath)
  return relative !== '.claude' && !relative.startsWith(`.claude${path.sep}`)
}

export function scoreDesignBeforeEdit({ events, dir }) {
  const editedOutside = editedPaths(events).filter((filePath) => isOutsideHarness(dir, filePath))
  const changedOutside = git(dir, 'status', '--porcelain', '--', '.', ':!.claude')
  if (editedOutside.length > 0) return verdict(false, `A project file was edited: ${editedOutside[0]}.`)
  if (changedOutside !== '') return verdict(false, 'The project files changed without a design.')
  return verdict(true, 'No project file was edited.')
}
